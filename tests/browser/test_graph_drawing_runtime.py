class TestParseDrawing:
    def test_parse_drawing_accepts_only_an_svg_element(self, page: Page, code_site_url: str):
        goto_graph(page, code_site_url + "/Dependency-Graph/")
        results = page.evaluate(
            """async () => {
                const graph = await import(new URL("-verso-data/Commands/graph.mjs",
                    document.baseURI).href);
                const svg = "http://www.w3.org/2000/svg";
                const cases = {
                    empty: "",
                    blank: "   \\n ",
                    nothing: null,
                    words: "not a drawing",
                    html: "<html xmlns='http://www.w3.org/1999/xhtml'><body>x</body></html>",
                    divWithSvg: "<div xmlns='" + svg + "'><svg xmlns='" + svg + "'/></div>",
                    noNamespace: "<svg width='1' height='1'><g/></svg>",
                    otherNamespace: "<svg xmlns='http://example.invalid/svg'/>",
                    truncated: "<svg xmlns='" + svg + "'><g>",
                    json: "{\\"svg\\": 1}",
                };
                const refused = {};
                for (const [name, text] of Object.entries(cases)) {
                    refused[name] = graph.parseDrawing(text) === null;
                }
                const ok = graph.parseDrawing(
                    "\\n  <svg xmlns='" + svg + "' width='3' height='4'><g class='graph'/></svg>\\n");
                return { refused, ok: !!ok && ok.localName === "svg" && ok.namespaceURI === svg &&
                    ok.ownerDocument === document };
            }"""
        )
        assert all(results["refused"].values()), results["refused"]
        assert results["ok"]


class TestSmallWindows:
    def test_resizing_the_window_refits_the_drawing(self, page: Page, code_site_url: str):
        goto_graph(page, code_site_url + "/Dependency-Graph/", width=1300)
        wide = page.evaluate(
            "() => document.querySelector('.bp_graph_canvas').clientWidth")
        page.set_viewport_size({"width": 900, "height": 800})
        page.wait_for_function(
            """(wide) => {
                const canvas = document.querySelector(".bp_graph_canvas");
                const svg = canvas.querySelector(":scope > svg");
                return canvas.clientWidth < wide - 100 &&
                    parseFloat(svg.getAttribute("width")) === canvas.clientWidth;
            }""",
            arg=wide,
        )
        inside = page.evaluate(
            """() => {
                const canvas = document.querySelector(".bp_graph_canvas").getBoundingClientRect();
                return Array.from(document.querySelectorAll(".bp_graph_canvas > svg g.node")).filter((n) => {
                    const r = n.getBoundingClientRect();
                    return r.left >= canvas.left - 1 && r.right <= canvas.right + 1;
                }).length;
            }"""
        )
        assert inside == 4

    def test_narrow_window_shows_the_graph_without_sideways_scroll(
        self, page: Page, large_site_url: str
    ):
        goto_graph(page, large_site_url + "/Dependency-Graph/", width=390, height=800)
        page.locator(".bp_graph_view_select").select_option("full")
        wait_for_graph_rendered(page)
        facts = page.evaluate(
            """async () => {
                const core = await import(new URL("-verso-data/Commands/graph-runtime-core.mjs",
                    document.baseURI).href);
                const svg = document.querySelector(".bp_graph_canvas > svg");
                const canvas = document.querySelector(".bp_graph_canvas").getBoundingClientRect();
                const visible = Array.from(svg.querySelectorAll("g.node")).filter((n) => {
                    const r = n.getBoundingClientRect();
                    return r.right > canvas.left && r.left < canvas.right &&
                        r.bottom > canvas.top && r.top < canvas.bottom;
                });
                return { scrollWidth: document.documentElement.scrollWidth,
                         innerWidth: window.innerWidth, canvasWidth: canvas.width,
                         scale: parseFloat(svg.getAttribute("data-bp-graph-scale")),
                         minimum: core.minReadableGraphScale, floor: core.wholeGraphScaleFloor,
                         readable: svg.getAttribute("data-bp-graph-readable"),
                         visible: visible.length };
            }"""
        )
        assert facts["scrollWidth"] <= facts["innerWidth"], facts
        assert facts["canvasWidth"] <= facts["innerWidth"], facts
        # readable on the roots, or whole at no less than the floor
        least = facts["minimum"] if facts["readable"] == "1" else facts["floor"]
        assert facts["scale"] >= least - 0.001 and facts["visible"] > 0, facts
        page.locator(".bp_graph_options_button").click()
        panel = page.locator(".bp_graph_options_popover")
        assert panel.is_visible()
        box = panel.bounding_box()
        assert box["x"] >= 0 and box["x"] + box["width"] <= 390 + 1


