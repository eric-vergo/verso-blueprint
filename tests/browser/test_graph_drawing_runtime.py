# The most the strict policy of the checks below leaves out for the page template that Verso
# writes: its inline scripts and handlers. No page loads a script from another host.
STRICT_POLICY = (
    "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; "
    "img-src 'self' data:; connect-src 'self'; object-src 'none'; base-uri 'self'"
)
# The least policy under which the site's pages work as a whole: the page template's own inline
# scripts are allowed, nothing else is.
TEMPLATE_POLICY = (
    "default-src 'self'; script-src 'self' 'unsafe-inline'; "
    "style-src 'self' 'unsafe-inline'; img-src 'self' data:; connect-src 'self'; "
    "object-src 'none'; base-uri 'self'"
)
TEMPLATE_BLOCKED = {"inline"}

RECORD_VIOLATIONS = """
window.__bpCsp = [];
document.addEventListener("securitypolicyviolation", (e) => {
    window.__bpCsp.push({ directive: e.violatedDirective, blocked: e.blockedURI });
});
"""


def graph_data_folder(site: Path) -> Path:
    folders = [p for p in (site / "-verso-data" / "blueprint-graph").iterdir() if p.is_dir()]
    assert len(folders) == 1, folders
    return folders[0]


def goto_graph(page: Page, url: str, width: int = 1200, height: int = 800) -> None:
    page.set_viewport_size({"width": width, "height": height})
    page.goto(url, wait_until="domcontentloaded", timeout=60000)
    wait_for_graph_rendered(page)


def set_direction(page: Page, direction: str) -> None:
    page.evaluate(
        "(d) => document.querySelector('.bp_graph_fullwidth').__bpGraphController.setDirection(d)",
        direction,
    )
    page.wait_for_function(
        """(d) => {
            const canvas = document.querySelector(".bp_graph_canvas");
            const block = document.querySelector(".bp_graph_fullwidth");
            const state = block.__bpGraphState;
            return canvas.getAttribute("data-bp-active-direction") === d &&
                state.renderFinalizedToken === state.renderToken;
        }""",
        arg=direction,
    )


def node_name_of_each(page: Page) -> dict[str, dict]:
    """Every drawn node's name and the box of its centre on screen."""
    return page.evaluate(
        """() => Object.fromEntries(
            Array.from(document.querySelectorAll(".bp_graph_canvas > svg g.node")).map((n) => {
                const r = n.getBoundingClientRect();
                return [n.getAttribute("data-bp-node-name"),
                        { x: r.left + r.width / 2, y: r.top + r.height / 2 }];
            }))"""
    )


class TestFirstDrawing:
    def test_labels_and_ids_are_in_the_page_source(self, code_site_dir: Path):
        html = (code_site_dir / "Dependency-Graph" / "index.html").read_text(encoding="utf-8")
        first = re.search(r'<div class="bp_graph_first_drawing"[^>]*>', html)
        assert first and 'data-variant="full"' in first.group(0)
        assert 'data-direction="TB"' in first.group(0) and 'data-pack="any"' in first.group(0)
        svg = html[first.end(): html.index("</div>", first.end())]
        assert len(re.findall(r'<g id="[^"]+" class="node[ "]', svg)) == 4
        assert svg.count("<script") == 0 and " on" not in re.sub(r"[^ ]+=\"[^\"]*\"", "", svg)
        for label in ("Demo.b", "Demo.c", "Demo.d", ">a<"):
            assert label in svg

    def test_no_request_for_a_layout_or_drawing_library(self, page: Page, code_site_url: str):
        requested: list[str] = []
        page.on("request", lambda request: requested.append(request.url))
        goto_graph(page, code_site_url + "/Dependency-Graph/")
        outside = [url for url in requested if not url.startswith(code_site_url)]
        # no request leaves the site: docstrings are rendered when the site is built
        assert outside == []
        assert not [url for url in requested if "vendor" in url or "d3" in url.lower()
                    or "graphviz" in url.lower() or url.endswith(".wasm")]
        assert page.evaluate(
            """() => ["d3", "Graphviz", "graphviz", "hpccWasm", "Viz"].every(
                (name) => typeof window[name] === "undefined")"""
        )

    def test_page_draws_when_every_request_outside_the_site_is_refused(
        self, page: Page, code_site_url: str
    ):
        def refuse_outside(route):
            if route.request.url.startswith(code_site_url) or route.request.url.startswith("data:"):
                route.continue_()
            else:
                route.abort("internetdisconnected")

        page.context.route("**/*", refuse_outside)
        try:
            goto_graph(page, code_site_url + "/Dependency-Graph/")
            assert page.locator(".bp_graph_canvas > svg g.node").count() == 4
        finally:
            page.context.unroute("**/*", refuse_outside)


class TestContentSecurityPolicy:
    def test_graph_draws_under_the_strict_policy(self, page: Page, code_site_dir: Path):
        """The drawings are fetched from the site and parsed as SVG: no inline script, no remote
        host, no image or connection outside the site. Under the strictest policy the graph still
        draws; the page template's own inline scripts are what the policy stops."""
        with serve_with_headers(code_site_dir, {"Content-Security-Policy": STRICT_POLICY}) as url:
            page.add_init_script(RECORD_VIOLATIONS)
            goto_graph(page, url + "/Dependency-Graph/")
            assert page.locator(".bp_graph_canvas > svg g.node").count() == 4
            set_direction(page, "LR")
            page.goto(url + "/Dependency-Graph/#ego=Demo.b&k=2", wait_until="domcontentloaded")
            wait_for_graph_rendered(page)
            violations = page.evaluate("window.__bpCsp")
        blocked = {(v["directive"].split("-")[0], v["blocked"]) for v in violations}
        assert {b for _, b in blocked} <= TEMPLATE_BLOCKED, violations
        assert {d for d, _ in blocked} == {"script"}, violations

    def test_no_violation_when_the_page_template_is_allowed(self, page: Page, code_site_dir: Path):
        with serve_with_headers(code_site_dir, {"Content-Security-Policy": TEMPLATE_POLICY}) as url:
            page.add_init_script(RECORD_VIOLATIONS)
            messages: list[str] = []
            page.on("console", lambda m: messages.append(m.text) if m.type == "error" else None)
            goto_graph(page, url + "/Dependency-Graph/")
            page.locator(".bp_graph_canvas > svg g.node").first.click()
            page.wait_for_selector(".bp_graph_preview:not([hidden])")
            set_direction(page, "BT")
            page.goto(url + "/Dependency-Graph/#ego=Demo.c&k=3", wait_until="domcontentloaded")
            wait_for_graph_rendered(page)
            violations = page.evaluate("window.__bpCsp")
        assert violations == [], violations
        assert [m for m in messages if "Content Security Policy" in m] == []


class TestPanAndZoom:
    def test_drag_pans_and_the_click_that_ends_it_opens_nothing(self, page: Page, code_site_url: str):
        goto_graph(page, code_site_url + "/Dependency-Graph/")
        before = graph_transform(page)
        start = node_centre(page, "Demo.c")
        page.mouse.move(start["x"], start["y"])
        page.mouse.down()
        page.mouse.move(start["x"] + 70, start["y"] + 30, steps=8)
        page.mouse.up()
        after = graph_transform(page)
        assert after != before
        moved = node_centre(page, "Demo.c")
        assert abs((moved["x"] - start["x"]) - 70) < 2 and abs((moved["y"] - start["y"]) - 30) < 2
        assert page.locator(".bp_graph_preview").first.is_hidden()
        assert "node=" not in page.evaluate("location.hash")
        # a press that does not move is a click on the node
        page.mouse.click(moved["x"], moved["y"])
        page.wait_for_selector(".bp_graph_preview:not([hidden]) .bp_node_view")
        assert page.evaluate("location.hash") == "#node=Demo.c"

    def test_a_press_that_moves_a_few_pixels_is_still_a_click(self, page: Page, code_site_url: str):
        goto_graph(page, code_site_url + "/Dependency-Graph/")
        before = graph_transform(page)
        target = node_centre(page, "Demo.b")
        page.mouse.move(target["x"], target["y"])
        page.mouse.down()
        page.mouse.move(target["x"] + 3, target["y"] + 2, steps=2)
        page.mouse.up()
        page.wait_for_selector(".bp_graph_preview:not([hidden]) .bp_node_view")
        assert graph_transform(page) == before

    def test_wheel_zooms_about_the_pointer(self, page: Page, code_site_url: str):
        goto_graph(page, code_site_url + "/Dependency-Graph/", height=900)
        # a smaller start leaves room to zoom in
        page.evaluate(
            """() => { const svg = document.querySelector(".bp_graph_canvas > svg");
                       svg.focus(); }"""
        )
        page.keyboard.press("-")
        page.keyboard.press("-")
        before = graph_scale(page)
        point = node_centre(page, "Demo.c")
        page.mouse.move(point["x"], point["y"])
        page.mouse.wheel(0, -300)
        page.wait_for_function(
            "(k) => parseFloat(document.querySelector('.bp_graph_canvas > svg')"
            ".getAttribute('data-bp-graph-scale')) > k * 1.2",
            arg=before,
        )
        after = node_centre(page, "Demo.c")
        # the point under the pointer stays under it
        assert abs(after["x"] - point["x"]) < 2 and abs(after["y"] - point["y"]) < 2
        assert after["width"] > point["width"] * 1.2
        zoomed = graph_scale(page)
        page.mouse.wheel(0, 600)
        page.wait_for_function(
            "(k) => parseFloat(document.querySelector('.bp_graph_canvas > svg')"
            ".getAttribute('data-bp-graph-scale')) < k * 0.8",
            arg=zoomed,
        )

    def test_keys_zoom_pan_and_fit(self, page: Page, code_site_url: str):
        goto_graph(page, code_site_url + "/Dependency-Graph/")
        page.locator(".bp_graph_canvas > svg").focus()
        fitted = graph_scale(page)
        fitted_transform = graph_transform(page)
        page.keyboard.press("-")
        smaller = graph_scale(page)
        assert abs(smaller - fitted * 0.8) < 0.01
        page.keyboard.press("+")
        page.keyboard.press("+")
        assert abs(graph_scale(page) - fitted * 0.8 * 1.25 * 1.25) < 0.01
        before = graph_transform(page)
        page.keyboard.press("ArrowLeft")
        assert graph_transform(page) != before
        page.keyboard.press("0")
        assert abs(graph_scale(page) - fitted) < 0.001
        assert graph_transform(page) == fitted_transform

    def test_nothing_is_animated(self, page: Page, code_site_url: str):
        page.emulate_media(reduced_motion="reduce")
        goto_graph(page, code_site_url + "/Dependency-Graph/")
        facts = page.evaluate(
            """() => {
                const svg = document.querySelector(".bp_graph_canvas > svg");
                const all = [svg, ...svg.querySelectorAll("*")];
                return {
                    animationElements: svg.querySelectorAll(
                        "animate, animateTransform, animateMotion, set").length,
                    transitions: all.filter((e) => {
                        const s = getComputedStyle(e);
                        return s.transitionDuration.split(",").some((d) => parseFloat(d) > 0) ||
                            s.animationName !== "none";
                    }).length,
                };
            }"""
        )
        assert facts == {"animationElements": 0, "transitions": 0}
        # a wheel step is applied at once: the scale is the whole step as soon as the event ran
        point = node_centre(page, "Demo.c")
        before = graph_scale(page)
        page.mouse.move(point["x"], point["y"])
        page.mouse.wheel(0, -100)
        page.wait_for_function(
            "(k) => parseFloat(document.querySelector('.bp_graph_canvas > svg')"
            ".getAttribute('data-bp-graph-scale')) !== k",
            arg=before,
        )
        settled = graph_scale(page)
        page.wait_for_timeout(300)
        assert graph_scale(page) == settled


