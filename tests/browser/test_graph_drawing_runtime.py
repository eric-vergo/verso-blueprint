"""Browser checks for the dependency graph's drawings (`Informal.GraphLayout`) and the page's own
pan and zoom (`createPanZoom` in `Commands/graph-runtime-core.mjs`).

Every view is laid out and drawn as inert SVG while the site is built. These checks use sites
generated by `vbp code-site`: the four-declaration fixture (`code_site_fixture/`) and a generated
graph of 384 declarations in two connected components and eight groups. They cover the first
drawing being in the page before any script runs, the drawings the page fetches for views,
directions and packing, a strict Content-Security-Policy, pan, wheel zoom about the pointer, keyboard
zoom, neighbourhood views mirrored for the opposite directions with upright labels, the notice for a
neighbourhood the site did not draw, `parseDrawing` refusing text that is not SVG, a readable
start on a large graph, resizing, a narrow window, reduced motion and the console staying quiet.
"""

